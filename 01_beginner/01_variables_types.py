"""01 - 变量与数据类型

学习目标:
    - 掌握 Python 基本数据类型
    - 理解变量赋值与命名规范
    - 了解 type()、isinstance() 的使用
"""

# ===== 1. 变量赋值 =====
# Python 是动态类型语言,无需声明类型
name = "Python"          # str 字符串类型,用双引号包裹文本
version = 3.11            # float 浮点数(带小数的数字)
pi = 3.14159              # float 浮点数,表示圆周率
is_fun = True             # bool 布尔类型,只有 True 和 False 两个值
nothing = None            # NoneType 空值,表示"什么都没有"

# 多重赋值
a, b, c = 1, 2, 3          # 一次性给三个变量分别赋值
x = y = z = 0              # 三个变量同时赋相同的值 0

# 交换两个变量(Python 特色)
m, n = 10, 20              # 先给 m 和 n 赋初值
m, n = n, m                # 直接交换两个变量的值,无需中间变量
print(f"交换后 m={m}, n={n}")  # 打印交换后的结果


# ===== 2. 基本数据类型 =====
print("\n--- 基本数据类型 ---")  # 打印分隔标题,\n 表示换行
print(type(name), type(version), type(pi), type(is_fun), type(nothing))  # 用 type() 查看每个变量的数据类型


# ===== 3. 数值运算 =====
print("\n--- 数值运算 ---")  # 打印数值运算部分的标题
print(f"整除 7 // 2 = {7 // 2}")              # // 是整除运算,只保留整数部分
print(f"取余 7 % 2 = {7 % 2}")                # % 是取余运算,得到除法的余数
print(f"幂运算 2 ** 10 = {2 ** 10}")          # ** 表示幂运算,2 的 10 次方
print(f"绝对值 abs(-5) = {abs(-5)}")          # abs() 是内置函数,返回数字的绝对值
print(f"四舍五入 round(3.14159, 2) = {round(3.14159, 2)}")  # round() 四舍五入,第二个参数是保留小数位数


# ===== 4. 字符串基础 =====
print("\n--- 字符串基础 ---")  # 打印字符串部分的标题
s1 = '单引号'                # 用单引号定义字符串
s2 = "双引号"                # 用双引号定义字符串,与单引号效果相同
s3 = """多行
字符串"""                   # 三个引号可以定义跨多行的字符串
s4 = r"原始字符串\n不会转义"   # r 前缀:原始字符串,\n 不会被当作换行符处理
s5 = f"格式化: {name} {version}"  # f-string(Python 3.6+),用 {} 嵌入变量值
print(s1, s2, s3, s4, s5, sep="\n")  # 打印所有字符串,sep 指定用换行符分隔


# ===== 5. 布尔值与逻辑运算 =====
print("\n--- 布尔值 ---")  # 打印布尔值部分的标题
print(f"bool(0)={bool(0)}, bool('')= {bool('')}, bool([])={bool([])}")  # 都是 False,0、空字符串、空列表都被视为假
print(f"bool(1)={bool(1)}, bool('x')={bool('x')}")                      # 都是 True,非零数字和非空字符串被视为真
print(f"短路求值: 0 and print('x') = {0 and print('x')}")  # 不执行,and 运算符遇到 False 就停止,后面的 print 不会执行


# ===== 6. 类型转换 =====
print("\n--- 类型转换 ---")  # 打印类型转换部分的标题
print(int("123"), float("3.14"), str(123), bool(0))  # 将字符串转整数、字符串转浮点数、数字转字符串、0 转布尔值
print(list("abc"), tuple([1, 2, 3]), set([1, 1, 2]))  # 字符串转列表、列表转元组、列表转集合(自动去重)


# ===== 7. 类型检查 =====
print("\n--- 类型检查 ---")  # 打印类型检查部分的标题
print(isinstance(123, int))           # 推荐写法,判断 123 是否是 int 类型,返回 True
print(isinstance(3.14, (int, float))) # 同时判断多种类型,3.14 是 float 所以返回 True


