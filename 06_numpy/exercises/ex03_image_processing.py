"""练习3: 图像处理入门

用 NumPy 模拟图像处理:
    - 图像本质上是三维数组 (高×宽×通道)
    - 实现灰度化、翻转、裁剪等操作
"""

import numpy as np                                # 导入 numpy 模块

# 创建一个模拟的 RGB 图像 (4×4 像素, 3通道)
# 每个像素值 0-255, 分别表示红(R)、绿(G)、蓝(B) 的强度
image = np.array([                                # 定义模拟图像数据
    [[255, 0, 0], [0, 255, 0], [0, 0, 255], [255, 255, 0]],   # 第1行: 红、绿、蓝、黄
    [[128, 0, 0], [0, 128, 0], [0, 0, 128], [128, 128, 0]],   # 第2行: 暗色版
    [[64, 64, 64], [128, 128, 128], [192, 192, 192], [255, 255, 255]],  # 第3行: 灰度渐变
    [[0, 0, 0], [100, 100, 100], [200, 200, 200], [50, 50, 50]],  # 第4行: 灰度
], dtype=np.uint8)                                # dtype=uint8 表示 0-255 范围

print("图像形状:", image.shape)                   # 打印 (4, 4, 3): 高4×宽4×3通道

# 1. 灰度化: 用加权平均将 RGB 转为单通道
# 人眼对绿色更敏感，所以权重: R*0.299 + G*0.587 + B*0.114
weights = np.array([0.299, 0.587, 0.114])         # 定义灰度转换权重
gray = np.dot(image, weights).astype(np.uint8)    # 矩阵乘法计算灰度值
print("灰度图形状:", gray.shape)                  # 打印 (4, 4)
print("灰度图:\n", gray)                          # 打印灰度矩阵

# 2. 水平翻转（左右翻转）
flipped_lr = image[:, ::-1, :]                    # 宽度方向步长-1，实现翻转
print("\n水平翻转后第1行:", flipped_lr[0, :, :])  # 打印翻转后第1行

# 3. 垂直翻转（上下翻转）
flipped_ud = image[::-1, :, :]                    # 高度方向步长-1
print("垂直翻转后第1行:", flipped_ud[0, :, :])    # 打印翻转后第1行

# 4. 裁剪: 取中心 2×2 区域
cropped = image[1:3, 1:3, :]                      # 取第1-2行、第1-2列的像素
print("\n裁剪后形状:", cropped.shape)             # 打印 (2, 2, 3)

# 5. 亮度调整: 增加所有像素值
bright = np.clip(image.astype(int) + 50, 0, 255).astype(np.uint8)  # 加50并限制在0-255
print("加亮后第1个像素:", bright[0, 0])           # 打印 [255 50 50]（原 [255 0 0]）

# 6. 通道分离
R = image[:, :, 0]                                # 取第0通道（红色）
G = image[:, :, 1]                                # 取第1通道（绿色）
B = image[:, :, 2]                                # 取第2通道（蓝色）
print("\n红通道:\n", R)                           # 打印红色通道矩阵

# 7. 反色（255 减去原值）
inverted = 255 - image                           # 每个像素值用255减
print("反色后第1个像素:", inverted[0, 0])         # 打印 [0 255 255]（原 [255 0 0]）
